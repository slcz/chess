"""
tests/test_sp_replay.py — the self-play replay browser's server side:
dataset index rows and one game's replay payload, plus the HTTP surface
(in-process server on an ephemeral port), over a real 2-game unit
generated by engine/build/selfplay.

Skipped without the binary + seed checkpoint (same convention as
test_selfplay_roundtrip, which shares its unit-generation step).
"""
from __future__ import annotations

import json
import subprocess
import threading
import urllib.request
from http.server import ThreadingHTTPServer
from pathlib import Path

import pytest

from chess_ai.selfplay.replay import game_payload, game_summary, make_handler
from chess_ai.selfplay.shard import read_unit

ROOT = Path(__file__).resolve().parent.parent
BIN = ROOT / "engine" / "build" / "selfplay"
CKPT = ROOT / "runs" / "policy_value_net_rope_25k.pt"

pytestmark = pytest.mark.skipif(
    not BIN.exists() or not CKPT.exists(),
    reason="selfplay binary or seed checkpoint not built/present",
)


@pytest.fixture(scope="module")
def unit(tmp_path_factory) -> Path:
    d = tmp_path_factory.mktemp("sp_replay")
    proc = subprocess.run(
        [str(BIN), str(CKPT), str(d), "2", "16", "2", "16", "10", "120",
         "4", "0.25", "0.3", "mps", "5"],
        capture_output=True, text=True, timeout=600, cwd=ROOT,
    )
    assert proc.returncode == 0, proc.stderr
    return d


def test_payloads(unit: Path) -> None:
    games = read_unit(unit)
    rows = [game_summary(g) for g in games]
    assert len(rows) == 2
    for r in rows:
        assert set(r) == {"idx", "plies", "result", "end", "open"}
        assert r["result"] in ("1-0", "0-1", "1/2-1/2")
        assert r["end"] in ("natural", "cap")

    g = games[0]
    pay = game_payload(g)
    assert pay["idx"] == g.game_index and len(pay["plies"]) == g.n_plies
    for i, p in enumerate(pay["plies"]):
        assert p["san"] and p["uci"] and p["fen"].count(" ") == 5
        assert 1 <= len(p["pi"]) <= 12
        probs = [prob for _, prob in p["pi"]]
        assert probs == sorted(probs, reverse=True) and probs[0] > 0
    # every ply's fen differs from the previous one (moves actually move)
    fens = [p["fen"] for p in pay["plies"]]
    assert len(set(fens)) == len(fens)


def test_http(unit: Path) -> None:
    srv = ThreadingHTTPServer(("127.0.0.1", 0), make_handler(str(unit)))
    t = threading.Thread(target=srv.serve_forever, daemon=True)
    t.start()
    base = f"http://127.0.0.1:{srv.server_address[1]}"
    try:
        meta = json.loads(urllib.request.urlopen(f"{base}/meta").read())
        assert meta["games"] == 2
        rows = json.loads(urllib.request.urlopen(f"{base}/games").read())
        assert len(rows) == 2
        pay = json.loads(
            urllib.request.urlopen(f"{base}/game?i={rows[0]['idx']}").read())
        assert pay["plies"]
        err = json.loads(urllib.request.urlopen(f"{base}/game?i=99999").read())
        assert "error" in err
        page = urllib.request.urlopen(f"{base}/").read().decode()
        assert "self-play replay" in page and "pibars" in page
    finally:
        srv.shutdown()
